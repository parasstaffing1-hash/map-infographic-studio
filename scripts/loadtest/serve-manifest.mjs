#!/usr/bin/env node
/**
 * serve-manifest.mjs — zero-dependency synthetic NDJSON shard-manifest host.
 *
 * The shard worker fetches `manifest.urlTemplate` with `{shard}` replaced by the
 * zero-padded (6 digit) shard index (see services/render-platform/src/ndjson.ts)
 * and parses every line with ManifestRecordSchema from
 * services/render-platform/src/contracts.ts. This server emits records that
 * validate against that schema so a batch load test has something to point at.
 *
 * Routes:
 *   GET /health                  -> { ok: true }
 *   GET /shards/<shard>.ndjson   -> N NDJSON ManifestRecord lines
 *   GET /anything-else.ndjson    -> same (any path ending in .ndjson works)
 *
 * The default MANIFEST_ALLOWED_HOSTS of the platform is "127.0.0.1,localhost",
 * so bind/point at 127.0.0.1 unless you widen that env var.
 *
 * Usage:
 *   node scripts/loadtest/serve-manifest.mjs --port 8899 --records-per-shard 25
 */

import { createServer } from 'node:http';
import { parseArgs } from 'node:util';

const HELP = `serve-manifest.mjs — synthetic NDJSON manifest host for the batch load test

Options:
  --port <n>                 Port to listen on (default: 8899)
  --records-per-shard <n>    ManifestRecords emitted per shard (default: 25)
  --rows <n>                 Data rows inside each record's project (default: 12)
  --host <addr>              Bind address (default: 127.0.0.1)
  --view-mode <mode>         viewMode stamped on each record (default: omitted,
                             so the batch request's viewMode is used)
  -h, --help                 Show this help

Point a batch job at it with:
  --manifest "http://127.0.0.1:8899/shards/{shard}.ndjson"
`;

const REGIONS = [
  'Andhra Pradesh', 'Bihar', 'Gujarat', 'Karnataka', 'Kerala', 'Madhya Pradesh',
  'Maharashtra', 'Odisha', 'Punjab', 'Rajasthan', 'Tamil Nadu', 'Telangana',
  'Uttar Pradesh', 'West Bengal', 'Assam', 'Haryana',
];

function parseCliArgs(argv) {
  const { values } = parseArgs({
    args: argv,
    options: {
      port: { type: 'string', default: '8899' },
      'records-per-shard': { type: 'string', default: '25' },
      rows: { type: 'string', default: '12' },
      host: { type: 'string', default: '127.0.0.1' },
      'view-mode': { type: 'string' },
      help: { type: 'boolean', short: 'h', default: false },
    },
    allowPositionals: false,
  });
  return values;
}

function positiveInt(raw, label) {
  const value = Number(raw);
  if (!Number.isInteger(value) || value < 1) {
    throw new Error(`${label} must be a positive integer (got ${JSON.stringify(raw)})`);
  }
  return value;
}

/**
 * Builds one object that satisfies StoredProjectSchema (strict): rows with
 * id/region/value/raw, a free-form config record, and annotations.
 */
export function buildProject(rowCount, seed) {
  const year = String(2019 + (seed % 6));
  const rows = Array.from({ length: rowCount }, (_, index) => {
    const region = REGIONS[(seed + index) % REGIONS.length];
    const value = Number((((seed * 37 + index * 13) % 1000) / 10).toFixed(1));
    return {
      id: `row-${seed}-${index}`,
      region,
      value,
      year,
      raw: { region, value, year, source: 'loadtest-synthetic' },
    };
  });

  return {
    rows,
    config: {
      title: `Load test project ${seed}`,
      subtitle: 'Synthetic data generated by scripts/loadtest/serve-manifest.mjs',
      palette: 'blues',
      valueColumn: 'value',
      regionColumn: 'region',
    },
    annotations: [],
    currentYear: year,
  };
}

/**
 * Builds one ManifestRecord line. `id` must match the SafeIdentifier regex
 * (^[a-zA-Z0-9][a-zA-Z0-9._:-]*$) and `outputName` must match ^[a-zA-Z0-9._-]+$.
 */
export function buildRecord(shard, index, rowCount, viewMode) {
  const seed = shard * 1_000 + index;
  const record = {
    id: `lt-${shard}-${index}`,
    project: buildProject(rowCount, seed),
    outputName: `lt-${shard}-${index}.png`,
  };
  if (viewMode) record.viewMode = viewMode;
  return record;
}

export function buildShardBody(shard, recordsPerShard, rowCount, viewMode) {
  const lines = [];
  for (let index = 0; index < recordsPerShard; index += 1) {
    lines.push(JSON.stringify(buildRecord(shard, index, rowCount, viewMode)));
  }
  return `${lines.join('\n')}\n`;
}

function shardIndexFromPath(pathname) {
  const match = pathname.match(/(\d+)(?=[^\d]*$)/);
  return match ? Number(match[1]) : 0;
}

export function createManifestServer({ recordsPerShard, rows, viewMode }) {
  return createServer((request, response) => {
    let pathname;
    try {
      pathname = new URL(request.url, 'http://localhost').pathname;
    } catch {
      response.writeHead(400).end('bad request');
      return;
    }

    if (pathname === '/health' || pathname === '/') {
      response.writeHead(200, { 'content-type': 'application/json' });
      response.end(JSON.stringify({ ok: true, recordsPerShard, rowsPerRecord: rows }));
      return;
    }

    if (!pathname.endsWith('.ndjson')) {
      response.writeHead(404, { 'content-type': 'application/json' });
      response.end(JSON.stringify({ error: 'not_found', hint: 'request a path ending in .ndjson' }));
      return;
    }

    const shard = shardIndexFromPath(pathname);
    const body = buildShardBody(shard, recordsPerShard, rows, viewMode);
    response.writeHead(200, {
      'content-type': 'application/x-ndjson',
      'content-length': Buffer.byteLength(body),
      'cache-control': 'no-store',
    });
    if (request.method === 'HEAD') response.end();
    else response.end(body);
  });
}

async function main() {
  const values = parseCliArgs(process.argv.slice(2));
  if (values.help) {
    process.stdout.write(HELP);
    return;
  }

  const port = positiveInt(values.port, '--port');
  const recordsPerShard = positiveInt(values['records-per-shard'], '--records-per-shard');
  const rows = positiveInt(values.rows, '--rows');
  const viewMode = values['view-mode'];

  const server = createManifestServer({ recordsPerShard, rows, viewMode });
  server.listen(port, values.host, () => {
    process.stdout.write(
      `manifest host listening on http://${values.host}:${port}\n` +
      `  records per shard : ${recordsPerShard}\n` +
      `  rows per record   : ${rows}\n` +
      `  url template      : http://${values.host}:${port}/shards/{shard}.ndjson\n`,
    );
  });

  const shutdown = () => server.close(() => process.exit(0));
  process.on('SIGINT', shutdown);
  process.on('SIGTERM', shutdown);
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('serve-manifest.mjs')) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  });
}
